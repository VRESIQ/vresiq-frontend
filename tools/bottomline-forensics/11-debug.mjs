import { chromium } from 'playwright';
import fs from 'fs';
const BASE='http://localhost:5180', RID='forensicresume0000000001';
const all=JSON.parse(fs.readFileSync('../resumes.json','utf8'));
const resume=all.find(r=>r.template==='template1'); resume._id=RID;
const user={id:'forensicuser',name:'Forensic Tester',email:'forensic@vresiq.local',subscriptionPlan:'free',emailVerified:true};
const b=await chromium.launch({headless:true});
const p=await b.newPage({viewport:{width:1680,height:1100}});
p.on('console',m=>console.log('CONSOLE',m.type(),m.text().slice(0,300)));
p.on('pageerror',e=>console.log('PAGEERROR',String(e).slice(0,500)));
await p.addInitScript(()=>sessionStorage.setItem('token','forensic-token'));
await p.route('**/api/**',r=>r.fulfill({status:200,contentType:'application/json',body:'{}'}));
await p.route(`**/api/resumes/${RID}`,r=>r.request().method()==='GET'?r.fulfill({status:200,contentType:'application/json',body:JSON.stringify(resume)}):r.fulfill({status:200,contentType:'application/json',body:'{}'}));
await p.route('**/api/auth/profile',r=>r.fulfill({status:200,contentType:'application/json',body:JSON.stringify(user)}));
await p.goto(`${BASE}/resume/${RID}/edit`,{waitUntil:'domcontentloaded'});
await p.waitForTimeout(6000);
console.log('ROOT LEN', await p.evaluate(()=>document.getElementById('root')?.innerHTML.length));
console.log('ROOT', (await p.evaluate(()=>document.getElementById('root')?.innerHTML||'')).slice(0,800));
await b.close();
